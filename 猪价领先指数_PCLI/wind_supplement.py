# ---- 计算官方出栏量 TTM 同比（季度）vs 屠宰量 TTM 同比 ----
def q_ttm_yoy():
    """季度官方出栏量 TTM（过去4季累计）同比"""
    keys = sorted(slaughter_quarter.keys())
    res = []
    for i, k in enumerate(keys):
        if i < 7:  # 需要前4季+前8季
            continue
        cur = sum(slaughter_quarter[keys[j]] for j in range(i-3, i+1))
        prev = sum(slaughter_quarter[keys[j]] for j in range(i-7, i-3))
        yoy = (cur/prev - 1) * 100
        res.append((k, cur, round(yoy, 2)))
    return res

