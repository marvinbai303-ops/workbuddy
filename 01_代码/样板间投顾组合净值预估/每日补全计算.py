def series(code):
    """含 11-17 的日涨跌序列；沿用 base.series_for 的日期对齐（港股 10-19 记 0）"""
    return b.series_for(code) + [R17[code]]


def cum(rets):
    v, out = 1.0, [1.0]
    for r in rets:
        v *= 1 + r / 100.0
        out.append(v)
    return out


def value_series(key, mode="sector"):
    """返回每日组合价值指数（10-09 = 1）"""
    f = FUNDS[key]
    codes = [c for c, _ in f["hold"]]
    ws = [w / 100.0 for _, w in f["hold"]]
    reb = [cum(series(c)) for c in codes]          # 索引 0 = 9/30 基准
    n = len(reb[0])
    if mode == "sector":
        cl = CLOSE[IDXMAP[key]]
        T = [v / cl[0] for v in cl]
    else:
        T = [sum(rb[d] for rb in reb) / len(reb) for d in range(n)]
    w_res = max(f["stock"] / 100.0 - sum(ws), 0.0)
    cash = 1 - f["stock"] / 100.0
    V = []
    for d in range(n):
        V.append(sum(ws[i] * reb[i][d] for i in range(len(ws))) + w_res * T[d] + cash)
    return V


