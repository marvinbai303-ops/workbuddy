# ---------------- 模型 ----------------
def cum_index(rets):
    """日涨跌幅(%)序列 -> 累计净值指数"""
    idx, v = [1.0], 1.0
    for r in rets:
        v *= 1 + r / 100.0
        idx.append(v)
    return idx


def build():
    names = list(HOLDINGS)
    w0 = [HOLDINGS[n][0] for n in names]
    # 个股累计指数：ci[k] = 第 k 日收盘相对 9/30 收盘
    ci = [cum_index(HOLDINGS[n][1]) for n in names]
    # 风格代理：等权披露持仓
    proxy = []
    for k in range(len(DATES) + 1):
        proxy.append(sum(c[k] for c in ci) / len(ci))
    w_res = STOCK_PCT - TOP10_PCT
    w_cash = 1 - STOCK_PCT
    return names, w0, ci, proxy, w_res, w_cash


def est_series(mode):
    """mode: 'naive' = 静态权重仅前十大; 'full' = 漂移 + 未披露股票用风格代理 + 现金
    返回与 DATES 对齐的 27 个日收益（ci[0]=9/30 基准，ci[j] 对应 DATES[j-1]）"""
    names, w0, ci, proxy, w_res, w_cash = build()
    out = []
    for j in range(1, len(ci[0])):
        if mode == "naive":
            r = sum(w0[i] * (ci[i][j] / ci[i][j - 1] - 1) for i in range(len(names)))
        else:
            v_prev = (sum(w0[i] * ci[i][j - 1] for i in range(len(names)))
                      + w_res * proxy[j - 1] + w_cash)
            v_now = (sum(w0[i] * ci[i][j] for i in range(len(names)))
                     + w_res * proxy[j] + w_cash)
            r = v_now / v_prev - 1 - FEE / 365.0
        out.append(r * 100)
    return out


def stats(est, act):
    e = [a - b for a, b in zip(est, act)]
    n = len(e)
    mae = sum(abs(x) for x in e) / n
    rmse = (sum(x * x for x in e) / n) ** 0.5
    me = sum(e) / n
    hit = sum(1 for x in e if abs(x) <= 0.20) / n
    return mae, rmse, me, hit, max(abs(x) for x in e)


def ols(x, y):
    n = len(x)
    mx, my = sum(x) / n, sum(y) / n
    sxx = sum((a - mx) ** 2 for a in x)
    sxy = sum((a - mx) * (b - my) for a, b in zip(x, y))
    b = sxy / sxx if sxx else 0.0
    a = my - b * mx
    ss_tot = sum((b_ - my) ** 2 for b_ in y)
    ss_res = sum((y_ - (a + b * x_)) ** 2 for x_, y_ in zip(x, y))
    return a, b, (1 - ss_res / ss_tot if ss_tot else 0.0)


def est_rolling(win=15):
    """M3：持仓隐含收益 + 滚动窗 β 校准（只用 t 日之前已公布净值，严格样本外）"""
    raw = est_series("full")
    act = NAV_RET
    out = []
    for t in range(len(act)):
        if t < win:
            out.append(raw[t])
            continue
        xs = raw[t - win:t]
        ys = act[t - win:t]
        a, b, _ = ols(xs, ys)
        out.append(a + b * raw[t])
    return out, raw


